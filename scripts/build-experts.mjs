// Compiles content/experts/*.md into src/lib/companion/experts.generated.ts so the
// expert profiles ship inside the server bundle (no runtime file reads on serverless hosts).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "content", "experts");
const out = path.join(root, "src", "lib", "companion", "experts.generated.ts");

const profiles = {};
for (const file of readdirSync(dir).filter((f) => f.endsWith(".md")).sort()) {
  const raw = readFileSync(path.join(dir, file), "utf8");
  // Drop the front matter; the body is the profile the model reads.
  profiles[file.replace(/\.md$/, "")] = raw.replace(/^---[\s\S]*?---\s*/, "").trim();
}

writeFileSync(
  out,
  `// Generated by scripts/build-experts.mjs from content/experts/*.md. Do not edit by hand.\n` +
    `export const EXPERT_PROFILES: Record<string, string> = ${JSON.stringify(profiles, null, 2)};\n`,
);
console.log(`experts: ${Object.keys(profiles).length} profiles -> ${path.relative(root, out)}`);
